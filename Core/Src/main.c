/**
  * @brief  Function implementing the ControlTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartControlTask */
void StartControlTask(void *argument)
{
  /* USER CODE BEGIN 5 */
	TickType_t xLastWakeTime = xTaskGetTickCount();
	static uint8_t send_counter = 0;
	ElevatorData_t dataSnapshot;
  /* Infinite loop */
  for(;;)
  {
	Encoder_Update(&encoder);
	DistanceFilter_Update(&filtr, sensor.distance);
	CMD_Process();
	Lift_PID_Update_Transparent(&liftPID, encoder.targetHeight, filtr.output);
	__HAL_TIM_SET_COMPARE(&htim13, TIM_CHANNEL_1, liftPID.out_pwm_up);
	__HAL_TIM_SET_COMPARE(&htim11, TIM_CHANNEL_1, liftPID.out_pwm_down);

	send_counter++;
	if (send_counter >= 5){
		send_counter = 0;

		dataSnapshot.dist_filtered = filtr.output;
		taskENTER_CRITICAL();
		dataSnapshot.dist_raw = sensor.distance;
		taskEXIT_CRITICAL();
		dataSnapshot.target_h = encoder.targetHeight;
		dataSnapshot.pwm_up = liftPID.out_pwm_up;
		dataSnapshot.pwm_down = liftPID.out_pwm_down;

		osMessageQueuePut(elevatorQueueHandle, &dataSnapshot, 0, 0);
	}

	vTaskDelayUntil(&xLastWakeTime, pdMS_TO_TICKS(25));
  }
  /* USER CODE END 5 */
}

